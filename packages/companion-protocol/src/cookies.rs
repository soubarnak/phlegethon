//! Optional session cookie hand-off — writes Netscape format for Core cookie channel.

use serde::{Deserialize, Serialize};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Session material from the extension (scoped to page origin).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct CompanionSession {
    #[serde(default)]
    pub cookies: Vec<CompanionCookie>,
}

impl CompanionSession {
    pub fn validate(&self) -> Result<(), String> {
        if self.cookies.is_empty() {
            return Err("session must include at least one cookie".to_string());
        }
        for cookie in &self.cookies {
            cookie.validate()?;
        }
        Ok(())
    }
}

/// One browser cookie exported by the extension.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompanionCookie {
    pub name: String,
    pub value: String,
    pub domain: String,
    #[serde(default = "default_path")]
    pub path: String,
    #[serde(default)]
    pub secure: bool,
    #[serde(default)]
    pub http_only: bool,
    /// Unix timestamp; 0 means session cookie.
    #[serde(default)]
    pub expiration_date: i64,
}

fn default_path() -> String {
    "/".to_string()
}

impl CompanionCookie {
    pub fn validate(&self) -> Result<(), String> {
        if self.name.trim().is_empty() {
            return Err("cookie name must not be empty".to_string());
        }
        if self.domain.trim().is_empty() {
            return Err("cookie domain must not be empty".to_string());
        }
        Ok(())
    }
}

/// Write cookies to a Netscape-format file for yt-dlp `--cookies`.
pub fn write_netscape_cookie_file(
    session: &CompanionSession,
    dir: &Path,
) -> Result<PathBuf, String> {
    session.validate()?;
    fs::create_dir_all(dir).map_err(|e| format!("create cookie dir: {e}"))?;
    let path = dir.join(format!("companion-{}.cookies.txt", uuid::Uuid::new_v4()));
    let mut file =
        fs::File::create(&path).map_err(|e| format!("create cookie file: {e}"))?;
    writeln!(file, "# Netscape HTTP Cookie File")
        .map_err(|e| format!("write cookie header: {e}"))?;
    writeln!(file, "# Generated by Phlegethon Chrome Companion")
        .map_err(|e| format!("write cookie header: {e}"))?;
    writeln!(file)
        .map_err(|e| format!("write cookie header: {e}"))?;

    for cookie in &session.cookies {
        let domain_flag = if cookie.domain.starts_with('.') {
            "TRUE"
        } else {
            "FALSE"
        };
        let secure = if cookie.secure { "TRUE" } else { "FALSE" };
        writeln!(
            file,
            "{}\t{}\t{}\t{}\t{}\t{}\t{}",
            cookie.domain,
            domain_flag,
            cookie.path,
            secure,
            cookie.expiration_date,
            cookie.name,
            cookie.value,
        )
        .map_err(|e| format!("write cookie row: {e}"))?;
    }

    if !path.is_absolute() {
        return Err(format!(
            "cookie file must be absolute, got: {}",
            path.display()
        ));
    }
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn netscape_file_contains_cookie_rows() {
        let session = CompanionSession {
            cookies: vec![CompanionCookie {
                name: "sid".to_string(),
                value: "abc123".to_string(),
                domain: ".example.com".to_string(),
                path: "/".to_string(),
                secure: true,
                http_only: true,
                expiration_date: 1_700_000_000,
            }],
        };
        let dir = tempfile::tempdir().unwrap();
        let path = write_netscape_cookie_file(&session, dir.path()).unwrap();
        let content = fs::read_to_string(&path).unwrap();
        assert!(content.contains("# Netscape HTTP Cookie File"));
        assert!(content.contains(".example.com\tTRUE\t/\tTRUE\t1700000000\tsid\tabc123"));
    }
}
